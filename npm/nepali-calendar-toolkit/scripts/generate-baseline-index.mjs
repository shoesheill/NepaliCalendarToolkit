import { readdirSync, writeFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Writes src/baselineData.ts: a STATIC import of every bundled baseline file, keyed by the
 * same CDN-relative path getData() asks for.
 *
 * The baseline used to be read with `require(`./data/${path}`)`, which works in Node but
 * breaks everywhere else — `require` is undefined in a browser, and no bundler can resolve
 * a template-literal specifier anyway. Static imports are resolvable by tsc, Node, and
 * every bundler, so the offline guarantee holds in the browser too.
 *
 * Generated at build time (before tsc) so adding a year to src/data needs no hand edit.
 */
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = join(root, "src", "data");

/** CDN-relative paths, e.g. "month-lengths.json", "Events/2083.json". */
function collect(dir, prefix = "") {
  const out = [];
  for (const entry of readdirSync(dir).sort()) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...collect(full, `${prefix}${entry}/`));
    else if (entry.endsWith(".json")) out.push(`${prefix}${entry}`);
  }
  return out;
}

const paths = collect(dataDir);
const ident = (p) => "_" + p.replace(/[^A-Za-z0-9]/g, "_");

const body = `// AUTO-GENERATED by scripts/generate-baseline-index.mjs — do not edit.
// Static imports so the bundled baseline resolves in Node, in bundlers and in browsers.
${paths.map((p) => `import ${ident(p)} from "./data/${p}";`).join("\n")}

/** Bundled baseline keyed by the CDN-relative path \`getData\` requests. */
export const BASELINE: Readonly<Record<string, unknown>> = {
${paths.map((p) => `  ${JSON.stringify(p)}: ${ident(p)},`).join("\n")}
};
`;

writeFileSync(join(root, "src", "baselineData.ts"), body);
console.log(`generated src/baselineData.ts with ${paths.length} baseline files`);
